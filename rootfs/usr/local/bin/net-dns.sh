#!/bin/bash
# net-dns.sh — 把 /etc/resolv.conf 指向某条链路的 DHCP DNS。
#
# 本板没有 systemd-resolved，networkd 拿到的 DNS 不会自己落到 /etc/resolv.conf。
# 这里用 bind mount 覆盖，只改运行态、不写 eMMC；重启后由开机流程重新建立。
# 用法： net-dns.sh [iface]   （缺省取默认路由所在接口）
set -u

IFACE="${1:-}"
if [ -z "$IFACE" ]; then
    IFACE=$(ip route show default 2>/dev/null | awk '{for (i = 1; i <= NF; i++) if ($i == "dev") { print $(i + 1); exit }}')
fi
[ -n "$IFACE" ] || { echo "net-dns: 找不到默认路由"; exit 1; }

# networkctl 会打印 "DNS: 172.20.10.1"；取第一条地址
DNS=$(networkctl status "$IFACE" --no-pager 2>/dev/null \
    | awk -F': *' '/^ *DNS:/{print $2; exit}' | awk '{print $1}')
[ -n "$DNS" ] || { echo "net-dns: $IFACE 没有可用的 DHCP DNS"; exit 1; }

TMP=/run/v200ai-resolv.conf
{
    echo "# generated by net-dns.sh for $IFACE at $(date '+%F %T')"
    echo "nameserver $DNS"
    echo "nameserver 223.5.5.5"
} > "$TMP"

# 已有绑定先拆掉，否则 mount --bind 会叠层
if grep -qE " /etc/resolv.conf " /proc/mounts; then
    umount /etc/resolv.conf || exit 1
fi
mount --bind "$TMP" /etc/resolv.conf || exit 1

echo "net-dns: nameserver $DNS（$IFACE）"
# AP 的 dnsmasq 也读 resolv.conf，重启它让客户端一起用新上游
if systemctl is-active --quiet dnsmasq; then
    systemctl try-restart dnsmasq >/dev/null 2>&1 || true
fi
